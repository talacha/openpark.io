// Units, sites, zones and slots: create, edit and retire through the real screens, and the links between them.
import { chromium } from 'playwright-core';
const API = 'http://localhost:3000', WEB = 'http://localhost:5173';
const sfx = Math.random().toString(36).slice(2, 8);
const call = (path, { token, tenant, method = 'POST', body } = {}) => fetch(API + path, { method, headers: { 'content-type': 'application/json', ...(token ? { authorization: `Bearer ${token}` } : {}), ...(tenant ? { 'x-tenant': tenant } : {}) }, body: body ? JSON.stringify(body) : undefined }).then((r) => r.json());
const ok = (c, m) => { if (!c) throw new Error(m); console.log('✓ ' + m); };
const su = await call('/v1/signup', { body: { email: `crud-${sfx}@example.com`, password: 'correct-horse-battery', organisation: `Crud ${sfx}`, country: 'US' } });
await call('/v1/me/profile', { method: 'PATCH', token: su.token, tenant: su.tenant.slug, body: { locale: 'en' } });
const T = su.tenant.slug;
const b = await chromium.launch({ channel: 'chrome' });
const p = await (await b.newContext({ viewport: { width: 1280, height: 1000 }, locale: 'en-US' })).newPage();
const errs = []; p.on('pageerror', (e) => errs.push(String(e))); p.on('console', (m) => { if (m.type() === 'error' && !/Failed to load resource/.test(m.text())) errs.push(m.text()); });
p.on('dialog', (d) => d.accept());
await p.goto(`${WEB}/login`); await p.fill('input[name=email]', `crud-${sfx}@example.com`); await p.fill('input[name=password]', 'correct-horse-battery'); await p.click('button.primary'); await p.waitForURL(/dashboard/);

// ---- units ----
await p.goto(`${WEB}/t/${T}/units`); await p.waitForSelector('form input[name=code]');
await p.fill('form input[name=code]', 'T1-101'); await p.fill('form input[name=name]', 'Tower 1, 101'); await p.fill('form input[name=floor]', '1'); await p.fill('form input[name=note]', 'corner flat');
await p.click('form button.primary'); await p.waitForSelector('tr:has-text("T1-101")');
let row = p.locator('tr', { hasText: 'T1-101' });
ok((await row.innerText()).includes('corner flat'), 'created a unit with floor and note');
await row.getByRole('button', { name: 'Edit' }).click();
await p.fill('form[aria-label] input[name=name]', 'Tower 1, flat 101'); await p.fill('form[aria-label] input[name=floor]', '2');
await p.selectOption('form[aria-label] select[name=site]', { index: 1 });
await p.locator('form[aria-label] button.primary').click();
await p.waitForSelector('tr:has-text("Tower 1, flat 101")');
row = p.locator('tr', { hasText: 'T1-101' });
ok(/DEMO-01/.test(await row.innerText()) && (await row.locator('td.num').innerText()) === '2', 'edited name, site and floor');
await p.fill('form input[name=code]', 'T1-102'); await p.fill('form input[name=name]', 'Spare'); await p.click('form button.primary'); await p.waitForSelector('tr:has-text("T1-102")');
await p.locator('tr', { hasText: 'T1-102' }).getByRole('button', { name: 'Remove' }).click();
await p.waitForFunction(() => !document.body.innerText.includes('T1-102'));
ok(true, 'deleted an unused unit');
await call('/v1/users', { token: su.token, tenant: T, body: { email: `res-${sfx}@example.com`, roles: ['resident'], unit: 'T1-101' } });
await p.reload(); await p.waitForSelector('tr:has-text("T1-101")');
ok(await p.locator('tr', { hasText: 'T1-101' }).getByRole('button', { name: 'Remove' }).isDisabled(), 'a unit with a resident cannot be removed');
await p.locator('tr', { hasText: 'T1-101' }).locator('a').first().click(); await p.waitForURL(/\/users$/);
ok(true, 'the resident name links to People');
await p.locator('tr', { hasText: `res-${sfx}@example.com` }).locator('a[href$="/units"]').click(); await p.waitForURL(/\/units$/);
ok(true, 'the unit code in People links back to Units');

// ---- parking ----
await p.goto(`${WEB}/t/${T}/parking`); await p.waitForSelector('[data-site=DEMO-01]');
await p.fill('form input[name=code]', 'ANNEX'); await p.fill('form input[name=name]', 'Annex'); await p.selectOption('form select[name=timezone]', 'America/Chicago'); await p.fill('form input[name=address]', '1 Main St');
await p.locator('form:has(input[name=address]) button.primary').click();
await p.waitForSelector('[data-site=ANNEX]');
ok(true, 'created a site');
const card = p.locator('[data-site=ANNEX]');
await card.getByRole('button', { name: 'Manage' }).click();
ok((await card.locator('input[name=aiThreshold]').getAttribute('type')) === 'number', 'AI threshold is a number field');
await card.locator('input[name=aiThreshold]').fill('0.9'); await card.locator('input[name=name]').first().fill('Annex building'); await card.locator('form:has(input[name=aiThreshold]) button.primary').click();
await p.waitForSelector('[data-site=ANNEX] h2:has-text("Annex building")');
ok(true, 'edited the site');
ok(await card.locator('.banner.warn').isVisible(), 'no zone yet: slot form explains instead of asking');
await card.locator('form:has(input[name=level])').last().locator('input[name=code]').fill('G1');
await card.locator('form:has(input[name=level])').last().locator('input[name=name]').fill('Ground');
await card.locator('form:has(input[name=level])').last().locator('input[name=level]').fill('0');
await card.getByRole('button', { name: 'Add zone' }).click();
await card.locator('tr:has-text("Ground")').waitFor();
ok(true, 'added a zone');
await card.locator('form:has(select[name=type])').locator('input[name=code]').fill('A1');
await card.locator('form:has(select[name=type])').locator('input[name=note]').fill('near the lift');
await card.getByRole('button', { name: 'Add slot' }).click();
await card.locator('tr:has-text("A1")').waitFor();
ok((await card.locator('tr:has-text("A1")').innerText()).includes('near the lift'), 'added a slot');
await card.locator('tr:has-text("A1")').getByRole('button', { name: 'Edit' }).click();
await card.locator('form[aria-label] select[name=status]').selectOption('out_of_service'); await card.locator('form[aria-label] button.primary').click();
await card.locator('tr:has-text("Out of service")').waitFor();
ok(true, 'edited the slot (status)');
ok(await card.locator('tr:has-text("Ground")').getByRole('button', { name: 'Remove' }).isDisabled(), 'a zone with slots cannot be removed');
await card.locator('tr:has-text("A1")').getByRole('button', { name: 'Remove' }).click();
await p.waitForFunction(() => ![...document.querySelectorAll('[data-site=ANNEX] tbody tr')].some((r) => r.textContent.includes('A1')));
await card.locator('tr:has-text("Ground")').getByRole('button', { name: 'Remove' }).click();
await p.waitForFunction(() => !document.querySelector('[data-site=ANNEX]').textContent.includes('Ground'));
ok(true, 'retired the slot, then removed the empty zone');
await card.getByRole('button', { name: 'Retire site' }).click();
await p.waitForSelector('[data-site=ANNEX]', { state: 'detached' });
ok(true, 'retired the site');
await p.locator('[data-site=DEMO-01]').getByRole('button', { name: 'Manage' }).click();
await p.locator('[data-site=DEMO-01] a[href$="/inventory"]').click(); await p.waitForURL(/\/inventory$/);
ok(true, 'the bulk-import link works');
// ---- integrations ----
await p.goto(`${WEB}/t/${T}/integrations`); await p.waitForSelector('form input[name=name]');
await p.fill('form input[name=name]', 'Gate PC'); await p.click('form:has(input[name=name]) button.primary');
await p.waitForSelector('.banner[role=status] code');
const key = await p.locator('.banner[role=status] code').innerText();
ok(key.length > 20, 'created an API key; the secret is shown once');
await p.reload(); await p.waitForSelector('tr:has-text("Gate PC")');
ok(!(await p.content()).includes(key), 'the key is not shown again after reload');
await p.locator('tr:has-text("Gate PC")').getByRole('button', { name: 'Revoke' }).click();
await p.locator('tr:has-text("Gate PC") .pill.warn').waitFor();
ok(true, 'revoked the key');
await p.fill('form input[name=url]', 'https://example.com/hook'); await p.click('form:has(input[name=url]) button.primary');
await p.locator('tr:has-text("example.com/hook")').waitFor();
await p.locator('tr:has-text("example.com/hook")').getByRole('button', { name: 'Edit' }).click();
await p.fill('form[aria-label] input[name=url]', 'https://example.com/v2'); await p.locator('form[aria-label] input[type=checkbox]').last().uncheck(); await p.locator('form[aria-label] button.primary').click();
await p.locator('tr:has-text("example.com/v2"):has-text("Paused")').waitFor();
ok(true, 'created, edited and paused a webhook');
await p.locator('tr:has-text("example.com/v2")').getByRole('button', { name: 'Remove' }).click();
await p.waitForFunction(() => !document.body.innerText.includes('example.com/v2'));
ok(true, 'deleted the webhook');
ok(errs.length === 0, 'no page errors' + (errs.length ? ': ' + errs.join(' | ') : ''));
await b.close();
